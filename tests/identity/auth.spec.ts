import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
const email = () => 'identity-test-'+randomUUID()+'@example.invalid';
const password = () => 'test-'+randomUUID();
const csrf = { 'X-NexQuiz-CSRF': '1' };
test('real register, profile, refresh replay, logout and offline Game identity', async ({ request }) => {
 const address = email(), secret = password();
 const registered = await request.post('/auth/api/v1/auth/register', { headers: csrf, data: { email: ' '+address.toUpperCase()+' ', password: secret, displayName: 'Identity test' } });
 expect(registered.status()).toBe(201);
 const body = await registered.json();
 expect(body.user.email).toBe(address); expect(body.user.passwordHash).toBeUndefined(); expect(body.refreshToken).toBeUndefined(); expect(body.expiresIn).toBe(300);
 const cookie = registered.headers()['set-cookie']!;
 expect(cookie).toContain('HttpOnly'); expect(cookie).toContain('SameSite=Strict'); expect(cookie).toContain('Path=/');
 const original = cookie.split(';')[0]!;
 const bearer = { Authorization: 'Bearer '+body.accessToken };
 expect((await request.get('/auth/api/v1/auth/profile', { headers: bearer })).status()).toBe(200);
 const identity = await request.get('/game/api/v1/identity', { headers: bearer });
 expect(identity.status()).toBe(200); expect((await identity.json()).userId).toBe(body.user.id);
 const duplicate = await request.post('/auth/api/v1/auth/register', { headers: csrf, data: { email: address, password: secret, displayName: 'Duplicate' } });
 expect(duplicate.status()).toBe(409);
 const refreshed = await request.post('/auth/api/v1/auth/refresh', { headers: csrf, data: {} });
 expect(refreshed.status()).toBe(200); const newer = await refreshed.json();
 expect(newer.accessToken === body.accessToken).toBe(false);
 const replay = await request.post('/auth/api/v1/auth/refresh', { headers: { ...csrf, Cookie: original }, data: {} });
 expect(replay.status()).toBe(401);
 expect((await request.get('/auth/api/v1/auth/profile', { headers: { Authorization: 'Bearer '+newer.accessToken } })).status()).toBe(401);
 const login = await request.post('/auth/api/v1/auth/login', { headers: csrf, data: { email: address, password: secret } });
 expect(login.status()).toBe(200); const active = await login.json();
 expect((await request.post('/auth/api/v1/auth/logout', { headers: csrf, data: {} })).status()).toBe(204);
 expect((await request.post('/auth/api/v1/auth/refresh', { headers: csrf, data: {} })).status()).toBe(401);
 expect((await request.get('/auth/api/v1/auth/profile', { headers: { Authorization: 'Bearer '+active.accessToken } })).status()).toBe(401);
 // Offline Game does not claim immediate revocation: access remains valid until exp.
 expect((await request.get('/game/api/v1/identity', { headers: { Authorization: 'Bearer '+active.accessToken } })).status()).toBe(200);
 expect((await request.post('/auth/api/v1/auth/logout', { headers: csrf, data: {} })).status()).toBe(204);
});
test('validation, CSRF, generic login failures, rate limit and public-only keys', async ({ request }) => {
 const input = { email: email(), password: password(), displayName: 'Security test' };
 expect((await request.post('/auth/api/v1/auth/register', { headers: { ...csrf, 'Content-Type': 'application/json' }, data: '{' })).status()).toBe(400);
 expect((await request.post('/auth/api/v1/auth/register', { headers: csrf, data: { ...input, password: 'a'.repeat(20000) } })).status()).toBe(413);
 expect((await request.post('/auth/api/v1/auth/register', { data: input })).status()).toBe(403);
 expect((await request.post('/auth/api/v1/auth/register', { headers: { ...csrf, Origin: 'https://evil.invalid' }, data: input })).status()).toBe(403);
 expect((await request.post('/auth/api/v1/auth/register', { headers: csrf, data: { ...input, password: 'short' } })).status()).toBe(400);
 expect((await request.post('/auth/api/v1/auth/register', { headers: csrf, data: { ...input, admin: true } })).status()).toBe(400);
 expect((await request.get('/auth/api/v1/auth/profile')).status()).toBe(401);
 expect((await request.get('/game/api/v1/identity', { headers: { Authorization: 'Bearer corrupted.token.value' } })).status()).toBe(401);
 for (let index=0; index<8; index++) expect((await request.post('/auth/api/v1/auth/login', { headers: csrf, data: { email: input.email, password: input.password } })).status()).toBe(401);
 const limited = await request.post('/auth/api/v1/auth/login', { headers: csrf, data: { email: input.email, password: input.password } });
 expect(limited.status()).toBe(429); expect(Number(limited.headers()['retry-after'])).toBeGreaterThan(0);
 const keys = await request.get('/auth/api/v1/.well-known/jwks.json'); expect(keys.status()).toBe(200);
 for (const key of (await keys.json()).keys) {
  expect(key.kty).toBe('RSA'); expect(key.alg).toBe('RS256');
  for (const field of ['d','p','q','dp','dq','qi']) expect(key[field]).toBeUndefined();
 }
});
